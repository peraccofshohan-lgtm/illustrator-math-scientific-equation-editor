#!/usr/bin/env node
/* Generates docs/TEST_REPORT.md from tests/results/summary.json (written by
 * `npm test`). Numbers in the report therefore always come from a real run. */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const s = JSON.parse(fs.readFileSync(path.join(root, 'tests', 'results', 'summary.json'), 'utf8'));
const pkg = require('../package.json');
const asset = path.join(root, 'release', 'Shohan_Khan_Illustrator_Math_Scientific_Equation_Editor.jsx');
const size = fs.existsSync(asset) ? fs.statSync(asset).size : 0;
const L = [];
L.push('# Test Report', '');
L.push('Generated by `node tools/test-report.js` from `tests/results/summary.json` (the output of `npm test`).', '');
L.push('| Item | Value |', '|---|---|');
L.push('| Version | ' + pkg.version + ' |');
L.push('| Run date (UTC) | ' + s.date + ' |');
L.push('| Runtime | Node.js ' + s.node + ' (script executed in a `vm` sandbox) |');
L.push('| Release asset size | ' + size + ' bytes |');
L.push('| Total tests | ' + s.total + ' |');
L.push('| Passed | ' + s.passed + ' |');
L.push('| Failed | ' + s.failed + ' |');
L.push('| Duration | ' + s.ms + ' ms |', '');
L.push('## What these tests do and do not prove', '');
L.push('- **Tested (automated, in Node.js):** the parser, serializer, AST, structural editor, semantics, chemistry engine, layout engine, formatting model, font resolution logic, persistence (with a real file system behind an ExtendScript `File`/`Folder` mock), the ScriptUI dialog wiring (against a ScriptUI mock), and the renderer\'s calls into a mock of the Illustrator DOM (object creation, naming, notes, placement, rollback).');
L.push('- **ES3 runtime check:** one suite runs the complete release script in a sandbox from which every ES5+ built-in (`Array.prototype.indexOf/map/forEach`, `JSON`, `Object.keys`, `String.prototype.trim`, `Date.now`, ...) has been deleted, emulating ExtendScript\'s ES3 library. The build also parses the asset with an ES3 parser (acorn, `ecmaVersion: 3`).');
L.push('- **Not tested:** the script has **not been run inside Adobe Illustrator** (no Illustrator installation was available). Actual on-screen ScriptUI appearance, real font measurement, real text rendering, `createOutline()`, file dialogs and keyboard event delivery are therefore **Not tested**. Mocks verify the script\'s logic, not Illustrator\'s behaviour.', '');
L.push('## Results by suite', '', '| Suite | Passed | Failed |', '|---|---|---|');
Object.keys(s.suites).forEach(k => L.push('| ' + k + ' | ' + s.suites[k].passed + ' | ' + s.suites[k].failed + ' |'));
L.push('');
L.push('## Mandatory extreme tests A–H', '');
L.push('| ID | Scenario | Result |', '|---|---|---|');
s.tests.filter(t => t.suite === 'regression-tests/extreme').forEach(t => {
  const m = /^([A-H]): (.*)$/.exec(t.name);
  L.push('| ' + (m ? m[1] : '') + ' | ' + (m ? m[2] : t.name) + ' | ' + (t.ok ? 'Pass' : '**Fail**') + ' |');
});
L.push('', '## All tests', '');
let cur = '';
s.tests.forEach(t => {
  if (t.suite !== cur) { cur = t.suite; L.push('', '### ' + cur, ''); }
  L.push('- ' + (t.ok ? '✅' : '❌') + ' ' + t.name.replace(/\|/g, '\\|'));
});
L.push('', '## Defects found and fixed by these tests', '');
L.push('Each has a regression test in `tests/regression-tests/regression.test.js`:', '');
L.push('- R5/R6: parsing and serialising long input was quadratic (20 000 characters took > 20 s); now linear.');
L.push('- R7: `U.toNumber` returned `undefined` for invalid input, so invalid stored font sizes became NaN; now returns `null` and falls back to defaults.');
L.push('- R8: CMYK colour conversion was called with the wrong arguments (colours in CMYK documents would have been empty).');
L.push('- R9: re-importing the same library file duplicated items renamed during the first import.');
L.push('- R12: nested superscripts had exponential layout cost (22 levels took 1.7 s, 40 levels would never finish); now linear.');
L.push('- R13: the node limit rejected the largest matrix the builder can create (100 × 100).');
L.push('- Also fixed: equation update shifted the equation by a few points (now preserves the baseline origin, even after the user moved it), list selection was lost after Rename, and tabs were selected by index (ScriptUI expects the tab object).');
L.push('', '## Reproduce', '', '```', 'npm install', 'npm test', 'node tools/test-report.js', '```', '');
fs.writeFileSync(path.join(root, 'docs', 'TEST_REPORT.md'), L.join('\n'));
console.log('Wrote docs/TEST_REPORT.md (' + s.passed + '/' + s.total + ' passed)');
